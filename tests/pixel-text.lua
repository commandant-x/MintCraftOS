package.path="./?.lua;"..package.path
local fonts=require("system.graphics.fonts")
local codec=require("system.graphics.text")
local Surface=require("system.graphics.surface")
local widgets=require("system.graphics.widgets")
local e=string.char(195,169)
assert(codec.decode(e,"utf8")==string.char(130))
assert(fonts.measure(e,2,"utf8")==12,"encoded measurement counts bytes")
assert(codec.decode("e"..string.char(204,129),"utf8")==string.char(130),"combining accent not composed")
assert(codec.decode(string.char(130),"auto")==string.char(130),"CraftOS byte changed")
assert(codec.decode(e,"cp437")==e,"explicit byte mode decoded Unicode")
assert(codec.decode("x"..string.char(240,159,154,128),"utf8")=="x?","unmapped codepoint disappeared")
assert(codec.decode(string.char(192,128),"utf8")=="??","overlong UTF8 accepted")
assert(codec.decode(string.char(237,160,128),"utf8")=="???","surrogate accepted")
assert(codec.decode(string.char(244,144,128,128),"utf8")=="????","out-of-range Unicode accepted")
assert(codec.decode(string.char(197,147),"utf8")=="oe")
local raw,truncated=codec.decode(string.rep("x",codec.limit+1))
assert(#raw==codec.limit and truncated,"unbounded display text")
local bounded=fonts.layout(raw,6,100000)
assert(#bounded.lines==4096 and bounded.overflow,"layout line cap missing")
local layout=fonts.layout("Bon"..e.." voyage",42,30,{lineSpacing=1})
assert(#layout.lines==2 and layout.lines[1].text=="Bon"..string.char(130) and layout.lines[2].text=="voyage")
assert(layout.width==36 and layout.height==19 and not layout.overflow)
layout=fonts.layout("abcdefghij",18,27)
assert(#layout.lines==3 and layout.lines[1].text=="abc" and layout.overflow)
layout=fonts.layout("a\r\nb\rc\n",12,36)
assert(#layout.lines==4 and layout.lines[4].text=="")
layout=fonts.layout("a\tb",48,9)
assert(layout.lines[1].text=="a   b")
layout=fonts.layout("ab",40,40,{scale=2,align="right",valign="bottom"})
assert(layout.lines[1].x==16 and layout.lines[1].y==22 and layout.width==24 and layout.height==18)
layout=fonts.layout("abcd",12,9,{wrap=false})
assert(layout.lines[1].text=="ab" and layout.overflow)
assert(#fonts.layout("abc",0,20).lines==0)
assert(#fonts.layout("abc",20,0).lines==0)
assert(not pcall(fonts.layout,"x",20,20,{lineSpacing=-1}))
assert(not pcall(fonts.layout,"x",20,20,{align="bad"}))
assert(not pcall(fonts.layout,"x",20,20,{scale=5}))
local actual,expected=Surface.new(40,20,15),Surface.new(40,20,15)
widgets.label(actual,0,0,e.."cole",30,0,15)
fonts.draw(expected,0,0,string.char(130).."cole",0,15)
for i,row in ipairs(actual.rows) do assert(row==expected.rows[i],"UTF8 label raster/width mismatch") end
local small=Surface.new(40,30,15)
small:setClip(5,5,20,15)
fonts.drawText(small,0,0,18,18,"AAAA\nBBBB",0,4,{scale=2})
for y,row in ipairs(small.rows) do for x=1,#row do
  if x<=5 or x>18 or y<=5 or y>18 then assert(row:byte(x)==15,"text escaped client or damage clip") end
end end
assert(small.clip.x==5 and small.clip.y==5,"text altered parent clip")
local original=e.."name"
widgets.input(small,{x=0,y=0,w=20,h=18},original,{desktop=15,text=0,muted=8,accent=9},true)
assert(original==e.."name","display conversion altered input")
print("pixel text: CP437/UTF8, accents, invalid encodings, wrapping, spacing, alignment, scale and nested clipping passed")
