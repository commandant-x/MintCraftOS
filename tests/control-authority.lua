package.path='./?.lua;'..package.path
local M=require('system.navigation.authority')
local function matrix(axes,values)
 local columns={} for i,v in ipairs(values) do columns[i]={id='command-'..i,values=v} end
 return assert(M.identify(axes,columns))
end
local balloon=matrix({'vertical'},{{vertical=.2}})
assert(balloon.rank==1 and balloon.axes.vertical.independent and not balloon.axes.yaw)
local ship=matrix({'forward','yaw'},{{forward=.2,yaw=-2},{forward=.2,yaw=2}})
assert(ship.rank==2 and ship.axes.forward.independent and ship.axes.yaw.independent)
local thrusters=matrix({'forward','right','vertical'},{{forward=1,right=0,vertical=0},{forward=0,right=1,vertical=0},{forward=0,right=0,vertical=1}})
assert(thrusters.rank==3 and thrusters.axes.right.independent)
local quad=matrix({'vertical','pitch','roll','yaw'},{{vertical=1,pitch=1,roll=1,yaw=1},{vertical=1,pitch=-1,roll=1,yaw=-1},{vertical=1,pitch=-1,roll=-1,yaw=1},{vertical=1,pitch=1,roll=-1,yaw=-1}})
assert(quad.rank==4 and quad.axes.roll.independent and not quad.axes.forward)
local asymmetric=matrix({'forward','yaw'},{{forward=.3,yaw=-1},{forward=.2,yaw=2}})
assert(asymmetric.rank==2 and asymmetric.axes.yaw.independent)
local offset=matrix({'forward','right','pitch'},{{forward=1,right=0,pitch=1},{forward=0,right=1,pitch=1}})
assert(offset.rank==2 and not offset.axes.pitch.independent and not offset.axes.forward.independent,'coupled response invented independent axes')
local broken=matrix({'forward','yaw'},{{forward=1,yaw=1},{forward=0,yaw=0}})
assert(broken.rank==1 and not broken.axes.forward.independent)
local heavier=matrix({'forward','yaw'},{{forward=.15,yaw=-.5},{forward=.1,yaw=1}})
assert(heavier.rank==2) -- Algebra only; no mass certificate is granted by this module.
assert(not M.identify({'forward','yaw'},{{id='a',values={forward=1}}}),'missing sensor fabricated zero response')
local singular=matrix({'forward','yaw'},{{forward=1,yaw=1},{forward=1,yaw=1.000001}})
assert(singular.rank==1 and not singular.axes.yaw.independent)
local redundant=matrix({'forward','yaw'},{{forward=1,yaw=1},{forward=1,yaw=1.0011},{forward=1,yaw=-1}})
assert(redundant.rank==2 and redundant.axes.yaw.independent,'redundant column spoiled a strong independent control subset')
assert(not M.identify({'forward','forward'},{{id='a',values={forward=1}}}))
assert(not M.identify({'forward'},{{id='a',values={forward=math.huge}}}))
assert(not M.identify({'forward'},{{id='a',values={forward=1}},extra={}}))
local braking=assert(M.braking({{brakeSpeed=2,brakingDistance=4,reactionTime=1},{brakeSpeed=1,brakingDistance=2,reactionTime=.5}}))
assert(braking.deceleration==.25 and braking.reactionTime==1 and braking.maxObservedSpeed==2)
local speed=assert(M.speed(braking,1))
assert(speed<2 and speed*braking.reactionTime+speed^2/(2*braking.deceleration)<=1+1e-8)
assert(M.speed(braking,0)==0 and M.speed(braking,100)==2)
assert(not M.braking({{brakingDistance=1,peakSpeed=2}}),'legacy distance guessed a braking envelope')
assert(not M.speed({deceleration=0,reactionTime=0,maxObservedSpeed=2},1))
local monitor=M.monitor()
local expected={forward=.2,yaw=0}
for i=1,7 do assert(not monitor:observe({at=i*.5,velocity={x=0,z=0},yawRate=0},expected,true)) end
assert(monitor:observe({at=4,velocity={x=0,z=0},yawRate=0},expected,true))
assert(not monitor:observe({at=4.5,velocity={x=.1,z=0},yawRate=0},expected,true) and monitor.samples==0)
assert(not monitor:observe({at=5,velocity={x=0,z=0},yawRate=0},expected,false) and monitor.samples==0)
assert(not monitor:observe({at=5.5,velocity={x=0,z=0},yawRate=0},{forward=0,yaw=0},true))
print('Control authority: nine simplified configurations, bounded matrix rank/coupling diagnostics, missing sensors, conservative measured braking and passive no-response evidence passed')
