-- Only run in a disposable CraftOS-PC directory; /source is a read-only mount.
local function write(path, content)
  fs.makeDir(fs.getDir(path))
  local h = assert(fs.open(path, "w"))
  h.write(content)
  h.close()
end
local function read(path)
  local h = assert(fs.open(path, "r"))
  local value = h.readAll()
  h.close()
  return value
end
local ok, err = pcall(function()
  shell.setDir("/")
  assert(shell.run("/source/install.lua"), "installation failed")
  local updated = require("system.services.updated")
  local originalVersion = read("/VERSION")
  write("/system/config/backup-test.cfg", "before")
  write("/apps/backup-test/nested/file.txt", "original nested file")
  write("/home/user/backup-test.txt", "user data")
  local backedUp, manifest = updated.createRollback("CraftOS filesystem test")
  assert(backedUp, tostring(manifest))
  local root = updated.rollbackRoot .. "/" .. manifest.id
  assert(read(root .. "/apps/backup-test/nested/file.txt") == "original nested file")
  write("/VERSION", "99.0.0")
  write("/system/config/backup-test.cfg", "after")
  write("/apps/backup-test/nested/file.txt", "changed")
  write("/apps/backup-test/new.txt", "added after backup")
  write("/home/user/backup-test.txt", "new user data")
  local restored, reason = updated.rollback()
  assert(restored, tostring(reason))
  assert(read("/VERSION") == originalVersion)
  assert(read("/system/config/backup-test.cfg") == "before")
  assert(read("/apps/backup-test/nested/file.txt") == "original nested file")
  assert(not fs.exists("/apps/backup-test/new.txt"))
  assert(read("/home/user/backup-test.txt") == "new user data")
  assert(not fs.exists("/var/tmp/mintcraft-restore"))
  write("/VERSION", "99.0.0")
  fs.move(root .. "/apps", root .. "/apps-hidden")
  local refused = updated.rollback()
  assert(not refused, "incomplete backup accepted")
  assert(read("/VERSION") == "99.0.0", "incomplete backup partially restored")
  fs.move(root .. "/apps-hidden", root .. "/apps")
  assert(updated.rollback())
  assert(read("/VERSION") == originalVersion)
  write("/backup-result.txt", "PASS: nested backup/restore, removed added app file, preserved home, rejected incomplete backup before writes")
end)
if not ok then write("/backup-result.txt", "FAIL: " .. tostring(err)) end
os.shutdown()
