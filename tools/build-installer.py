#!/usr/bin/env python3
"""Portable equivalent of build-installer.ps1; normalize only CRLF in sources."""
from pathlib import Path
from packed_source import pack

root = Path(__file__).resolve().parent.parent
paths = {Path(name) for name in ('boot.lua', 'startup.lua', 'VERSION')}
for name in ('system', 'apps', 'home', 'packages'):
    directory = root / name
    if directory.exists():
        paths.update(p.relative_to(root) for p in directory.rglob('*') if p.is_file())
parts = ['-- Generated by tools/build-installer.ps1. Run from CraftOS shell.\n',
         '-- MintCraft installer protocol: 2\n', 'local files = {\n']
for path in sorted(paths, key=lambda p: p.as_posix().lower()):
    content = (root / path).read_bytes().decode('utf-8').replace('\r\n', '\n')
    content = pack(path.as_posix(), content)
    delimiter = '='
    while ']' + delimiter + ']' in content:
        delimiter += '='
    parts.extend(['  ["' + path.as_posix() + '"] = [' + delimiter + '[\n',
                  content, ']' + delimiter + '],\n'])
parts.extend(['}\n',
              'local factory = assert(load(files["system/libraries/installer.lua"], "installer", "t", _ENV))\n',
              'factory().install(files, mintcraftInstallOptions)\n',
              'print("MintCraft OS installed. Reboot to start.")\n'])
(root / 'install.lua').write_bytes(''.join(parts).encode('utf-8'))
