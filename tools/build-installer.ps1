$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$bundlePaths = @('boot.lua', 'startup.lua', 'VERSION')
foreach ($directory in @('system', 'apps', 'home', 'packages')) {
  $absolute = Join-Path $projectRoot $directory
  if (Test-Path -LiteralPath $absolute) {
    $bundlePaths += Get-ChildItem -LiteralPath $absolute -Recurse -File | ForEach-Object {
      $_.FullName.Substring($projectRoot.Length + 1).Replace('\', '/')
    }
  }
}
$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('-- Generated by tools/build-installer.ps1. Run from CraftOS shell.')
[void]$builder.AppendLine('-- MintCraft installer protocol: 2')
[void]$builder.AppendLine('local files = {')
foreach ($relative in ($bundlePaths | Sort-Object -Unique)) {
  $content = [IO.File]::ReadAllText((Join-Path $projectRoot $relative)).Replace("`r`n", "`n")
  $delimiter = '='
  while ($content.Contains(']' + $delimiter + ']')) { $delimiter += '=' }
  [void]$builder.AppendLine('  ["' + $relative + '"] = [' + $delimiter + '[')
  [void]$builder.Append($content)
  [void]$builder.AppendLine(']' + $delimiter + '],')
}
[void]$builder.AppendLine('}')
[void]$builder.AppendLine('local factory = assert(load(files["system/libraries/installer.lua"], "installer", "t", _ENV))')
[void]$builder.AppendLine('factory().install(files, mintcraftInstallOptions)')
[void]$builder.AppendLine('print("MintCraft OS installed. Reboot to start.")')
[IO.File]::WriteAllText((Join-Path $projectRoot 'install.lua'), $builder.ToString(), [Text.UTF8Encoding]::new($false))
